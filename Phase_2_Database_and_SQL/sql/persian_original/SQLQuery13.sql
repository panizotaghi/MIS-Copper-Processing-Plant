-- تحلیل تغییرات روزانه وزن محموله‌ها
SELECT 
    [تاریخ ارسال],
    SUM([وزن خشک]) AS [وزن روزانه],
    SUM([وزن خشک]) - LAG(SUM([وزن خشک])) OVER (ORDER BY [تاریخ ارسال]) AS [تغییر وزن]
FROM Shipment
WHERE [تاریخ ارسال] BETWEEN '2025-01-01' AND '2025-06-01'
GROUP BY [تاریخ ارسال]
ORDER BY [تاریخ ارسال];
