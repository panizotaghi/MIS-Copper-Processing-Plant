-- تحلیل هزینه مصرف انرژی بر اساس نوع انرژی و تاریخ
SELECT 
    [نوع انرژی],
    [تاریخ مصرف],
    SUM([هزینه مصرف]) AS [مجموع هزینه],
    SUM([هزینه مصرف]) - LAG(SUM([هزینه مصرف])) OVER (PARTITION BY [نوع انرژی] ORDER BY [تاریخ مصرف]) AS [تغییرات هزینه]
FROM EnergyUsage
WHERE [تاریخ مصرف] BETWEEN '2025-01-01' AND '2025-06-01'
GROUP BY [نوع انرژی], [تاریخ مصرف]
ORDER BY [نوع انرژی], [تاریخ مصرف];
